package com.nexustools.genericui.style.css

/**
 * Canonical enumeration of standard W3C CSS properties supported by [ComponentStyle] and [ComputedStyle].
 */
enum class CssProperty(val cssName: String) {
    BACKGROUND_COLOR("background-color"),
    BACKGROUND_IMAGE("background-image"),
    BACKGROUND_SIZE("background-size"),
    BACKGROUND_POSITION("background-position"),
    BACKGROUND_REPEAT("background-repeat"),
    BACKGROUND_ATTACHMENT("background-attachment"),
    BACKGROUND_CLIP("background-clip"),
    BACKGROUND_ORIGIN("background-origin"),
    COLOR("color"),
    ACCENT_COLOR("accent-color"),
    OPACITY("opacity"),
    DISPLAY("display"),
    VISIBILITY("visibility"),
    POSITION("position"),
    TOP("top"),
    RIGHT("right"),
    BOTTOM("bottom"),
    LEFT("left"),
    WIDTH("width"),
    HEIGHT("height"),
    MIN_WIDTH("min-width"),
    MIN_HEIGHT("min-height"),
    MAX_WIDTH("max-width"),
    MAX_HEIGHT("max-height"),
    MARGIN("margin"),
    MARGIN_TOP("margin-top"),
    MARGIN_RIGHT("margin-right"),
    MARGIN_BOTTOM("margin-bottom"),
    MARGIN_LEFT("margin-left"),
    PADDING("padding"),
    PADDING_TOP("padding-top"),
    PADDING_RIGHT("padding-right"),
    PADDING_BOTTOM("padding-bottom"),
    PADDING_LEFT("padding-left"),
    BORDER_WIDTH("border-width"),
    BORDER_STYLE("border-style"),
    BORDER_COLOR("border-color"),
    BORDER_RADIUS("border-radius"),
    BOX_SHADOW("box-shadow"),
    TEXT_SHADOW("text-shadow"),
    FONT_FAMILY("font-family"),
    FONT_SIZE("font-size"),
    FONT_WEIGHT("font-weight"),
    FONT_STYLE("font-style"),
    LINE_HEIGHT("line-height"),
    LETTER_SPACING("letter-spacing"),
    TEXT_ALIGN("text-align"),
    TEXT_DECORATION("text-decoration"),
    TEXT_TRANSFORM("text-transform"),
    TEXT_OVERFLOW("text-overflow"),
    WHITE_SPACE("white-space"),
    WORD_BREAK("word-break"),
    VERTICAL_ALIGN("vertical-align"),
    FLEX_DIRECTION("flex-direction"),
    FLEX_WRAP("flex-wrap"),
    JUSTIFY_CONTENT("justify-content"),
    ALIGN_ITEMS("align-items"),
    ALIGN_SELF("align-self"),
    ALIGN_CONTENT("align-content"),
    FLEX_GROW("flex-grow"),
    FLEX_SHRINK("flex-shrink"),
    FLEX_BASIS("flex-basis"),
    GAP("gap"),
    ROW_GAP("row-gap"),
    COLUMN_GAP("column-gap"),
    OVERFLOW("overflow"),
    OVERFLOW_X("overflow-x"),
    OVERFLOW_Y("overflow-y"),
    CURSOR("cursor"),
    POINTER_EVENTS("pointer-events"),
    USER_SELECT("user-select"),
    OBJECT_FIT("object-fit"),
    ASPECT_RATIO("aspect-ratio"),
    Z_INDEX("z-index"),
    TRANSFORM("transform"),
    TRANSFORM_ORIGIN("transform-origin"),
    TRANSITION("transition"),
    FILTER("filter"),
    BACKDROP_FILTER("backdrop-filter"),
    BOX_SIZING("box-sizing"),
    FLOAT("float"),
    CLEAR("clear");

    companion object {
        private val BY_NAME: Map<String, CssProperty> = entries.associateBy { it.cssName }

        fun fromCssName(name: String): CssProperty? =
            BY_NAME[name.trim().lowercase()]
    }
}

/**
 * Anchor alignment for a floating layer ([LayerSizingMode.FLOAT]) within a [LayeredLayout].
 */
enum class LayerAlignment {
    TOP_START,
    TOP_CENTER,
    TOP_END,
    CENTER_START,
    CENTER,
    CENTER_END,
    BOTTOM_START,
    BOTTOM_CENTER,
    BOTTOM_END
}

    private class ThreadSafeContainerNativeImpl(prefix: String) :
        ThreadSafeNativeImpl(prefix), ContainerNativeImpl<Any> {
        val childImpls: MutableList<NativeImpl<*>> = Collections.synchronizedList(mutableListOf())

        override fun addChildNative(childImpl: NativeImpl<*>, index: Int) {
            synchronized(childImpls) {
                childImpls.remove(childImpl)
                val safeIndex = if (index < 0 || index > childImpls.size) childImpls.size else index
                childImpls.add(safeIndex, childImpl)
            }
        }

        override fun removeChildNative(childImpl: NativeImpl<*>) {
            synchronized(childImpls) { childImpls.remove(childImpl) }
        }

        override fun clearChildrenNative() {
            synchronized(childImpls) { childImpls.clear() }
        }
    }


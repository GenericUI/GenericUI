    @Test
    fun concurrentEnsureNativeImplAndContainerAttachmentNeverCreateBlankDuplicates() {
        val factory = ConcurrentCountingNativeFactory()
        GenericUI.initialize(factory)

        repeat(20) { iteration ->
            factory.buttonCreateCount.set(0)
            factory.containerCreateCount.set(0)

            val window = Window("Concurrent-$iteration")
            val row = Container("row").apply {
                id = "row-$iteration"
            }
            val pinBtn = Button("Pin", type = BootstrapType.INFO).apply {
                id = "btn-pin-$iteration"
                isVisible = true
            }
            val gearBtn = Button("Gear", type = BootstrapType.SECONDARY).apply {
                id = "btn-gear-$iteration"
                isVisible = true
            }
            row.addChild(pinBtn)
            row.addChild(gearBtn)
            window.setContent(row)
            window.ExplicitFactory = factory

            val threads = 8
            val startGate = CountDownLatch(1)
            val doneGate = CountDownLatch(threads)
            val failures = ConcurrentLinkedQueue<Throwable>()
            val pinImpls = ConcurrentHashMap.newKeySet<NativeImpl<*>>()

            for (t in 0 until threads) {
                Thread({
                    try {
                        startGate.await()
                        if (t % 2 == 0) {
                            val realizedRow = row.ensureNativeImpl()
                            row.syncStateToNativeInternal()
                            assertTrue(realizedRow != null)
                        } else {
                            val realizedPin = pinBtn.ensureNativeImpl() as ThreadSafeButtonNativeImpl
                            // Must never observe an un-synced blank native impl while another thread is initializing it.
                            assertEquals("Pin", realizedPin.getText())
                            assertEquals("btn-pin-$iteration", realizedPin.attributes["id"])
                            pinImpls.add(realizedPin)
                            gearBtn.ensureNativeImpl()
                        }
                    } catch (err: Throwable) {
                        failures.add(err)
                    } finally {
                        doneGate.countDown()
                    }
                }, "realize-stress-$t").start()
            }

            startGate.countDown()
            assertTrue(doneGate.await(10, TimeUnit.SECONDS))
            assertTrue(failures.isEmpty(), "Concurrent realization failed: ${failures.firstOrNull()}")

            assertEquals(1, factory.containerCreateCount.get())
            assertEquals(2, factory.buttonCreateCount.get())
            assertEquals(1, pinImpls.size)
            assertSame(pinBtn.nativeImpl, pinImpls.single())

            val rowNative = row.nativeImpl as ThreadSafeContainerNativeImpl
            assertEquals(
                listOf(pinBtn.nativeImpl, gearBtn.nativeImpl),
                synchronized(rowNative.childImpls) { rowNative.childImpls.toList() }
            )

            window.dispose()
        }
    }

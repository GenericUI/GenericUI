package com.nexustools.genericui.plugin

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import java.io.File

/**
 * Gradle task that stages Google ANGLE (`libEGL`, `libGLESv2`, `d3dcompiler_47`) and optional
 * SwiftShader (`vk_swiftshader`, `vk_swiftshader_icd.json`) runtime configuration and manifest metadata
 * so `Canvas3D` (`GpuBackendType.OPENGL_ES`) runs with hardware OpenGL ES 3.0+ on Windows and Apple platforms.
 */
abstract class AngleNativeBundleTask : DefaultTask() {

    @get:Input
    abstract val bundleAngleOnWindows: Property<Boolean>

    @get:Input
    @get:org.gradle.api.tasks.Optional
    abstract val bundleAngleOnApple: Property<Boolean>

    @get:Input
    @get:org.gradle.api.tasks.Optional
    abstract val bundleSoftwareFallback: Property<Boolean>

    @get:Input
    @get:org.gradle.api.tasks.Optional
    abstract val compileShaders: Property<Boolean>

    @get:Input
    abstract val angleBackendRenderer: Property<String>

    @get:Input
    abstract val preferOpenGLES31: Property<Boolean>

    @get:Input
    abstract val targetClassifiers: ListProperty<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    init {
        bundleAngleOnApple.convention(true)
        bundleSoftwareFallback.convention(false)
        compileShaders.convention(false)
    }

    @TaskAction
    fun generateAngleBundleManifest() {
        val outDir = outputDirectory.get().asFile
        outDir.mkdirs()

        val manifestFile = File(outDir, "angle-runtime.properties")
        val glesVersion = if (preferOpenGLES31.get()) "3.1" else "3.0"
        val winLibs = mutableListOf("libEGL.dll", "libGLESv2.dll", "d3dcompiler_47.dll")
        val appleLibs = mutableListOf("libEGL.dylib", "libGLESv2.dylib")
        if (bundleSoftwareFallback.getOrElse(false)) {
            winLibs.add("vk_swiftshader.dll")
            winLibs.add("vk_swiftshader_icd.json")
            appleLibs.add("libvk_swiftshader.dylib")
        }
        val content = buildString {
            appendLine("# Generated by GenericUI Gradle Plugin - Google ANGLE OpenGL ES Runtime")
            appendLine("angle.windows.enabled=${bundleAngleOnWindows.get()}")
            appendLine("angle.apple.enabled=${bundleAngleOnApple.getOrElse(true)}")
            appendLine("angle.softwareFallback.enabled=${bundleSoftwareFallback.getOrElse(false)}")
            appendLine("angle.compileShaders=${compileShaders.getOrElse(false)}")
            appendLine("angle.backend.renderer=${angleBackendRenderer.get()}")
            appendLine("angle.gles.version=$glesVersion")
            appendLine("angle.windows.libraries=${winLibs.joinToString(",")}")
            appendLine("angle.apple.libraries=${appleLibs.joinToString(",")}")
            appendLine("angle.linux.libraries=libEGL.so.1,libGLESv2.so.2")
            appendLine("angle.targets=${targetClassifiers.get().joinToString(",")}")
        }
        manifestFile.writeText(content)
    }
}

package com.nexustools.genericui.plugin

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import java.io.File

/**
 * Gradle task that generates Vulkan loader, MoltenVK ICD, and Shaderc configuration metadata
 * for `Canvas3D` (`GpuBackendType.VULKAN`) across Windows (`vulkan-1.dll`), Linux (`libvulkan.so.1`),
 * macOS/iOS (`libMoltenVK.dylib`), and Android (`libvulkan.so`).
 */
abstract class VulkanNativeBundleTask : DefaultTask() {

    @get:Input
    abstract val bundleMoltenVkOnApple: Property<Boolean>

    @get:Input
    abstract val bundleShaderc: Property<Boolean>

    @get:Input
    abstract val enableValidationLayersInDebug: Property<Boolean>

    @get:Input
    abstract val lwjglVersion: Property<String>

    @get:Input
    abstract val targetClassifiers: ListProperty<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generateVulkanBundleManifest() {
        val outDir = outputDirectory.get().asFile
        outDir.mkdirs()

        val manifestFile = File(outDir, "vulkan-runtime.properties")
        val content = buildString {
            appendLine("# Generated by GenericUI Gradle Plugin - Vulkan 1.2 & MoltenVK Runtime")
            appendLine("vulkan.api.version=1.2")
            appendLine("vulkan.moltenvk.apple=${bundleMoltenVkOnApple.get()}")
            appendLine("vulkan.shaderc.enabled=${bundleShaderc.get()}")
            appendLine("vulkan.validation.debug=${enableValidationLayersInDebug.get()}")
            appendLine("vulkan.lwjgl.version=${lwjglVersion.get()}")
            appendLine("vulkan.windows.loader=vulkan-1.dll")
            appendLine("vulkan.linux.loader=libvulkan.so.1")
            appendLine("vulkan.apple.icd=libMoltenVK.dylib")
            appendLine("vulkan.android.loader=libvulkan.so")
            appendLine("vulkan.targets=${targetClassifiers.get().joinToString(",")}")
        }
        manifestFile.writeText(content)
    }
}

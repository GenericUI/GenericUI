package com.nexustools.genericui.plugin

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.Optional
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import java.io.File
import java.nio.ByteBuffer
import java.nio.ByteOrder

/**
 * Gradle task that stages the Desktop Chromium/NJS `WebView` helper process executable
 * (`genericui-webview-process.exe` on Windows, `genericui-webview-process` on macOS and Linux)
 * into `build/generated/genericui/nativeBundle/webview/<platform>/<mode>/`.
 */
abstract class WebViewNativeProcessBundleTask : DefaultTask() {

    @get:Input
    @get:Optional
    abstract val webViewEnabled: Property<Boolean>

    @get:Input
    @get:Optional
    abstract val genericUiRootPath: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    init {
        webViewEnabled.convention(true)
    }

    @TaskAction
    fun stageWebViewProcessBinaries() {
        val outDir = outputDirectory.get().asFile
        outDir.mkdirs()

        val manifestFile = File(outDir, "webview-process-runtime.properties")
        manifestFile.writeText(
            buildString {
                appendLine("# Generated by GenericUI Gradle Plugin - Desktop WebView Helper Process")
                appendLine("webview.desktop.enabled=${webViewEnabled.getOrElse(true)}")
                appendLine("webview.windows.executable=$WINDOWS_EXE_NAME")
                appendLine("webview.macos.executable=$POSIX_EXE_NAME")
                appendLine("webview.linux.executable=$POSIX_EXE_NAME")
                appendLine("webview.ipc.protocol=chromium-mojo-njs-1.0")
            }
        )

        if (!webViewEnabled.getOrElse(true)) {
            return
        }

        val rootDir = genericUiRootPath.orNull?.takeIf { it.isNotBlank() }?.let { File(it) }
        stageWindowsWebViewProcess(File(outDir, "windows"), rootDir)
        stageMacosWebViewProcess(File(outDir, "macos"), rootDir)
        stageLinuxWebViewProcess(File(outDir, "linux"), rootDir)
    }

    private fun stageWindowsWebViewProcess(winBaseDir: File, genericUiRoot: File?) {
        winBaseDir.mkdirs()
        val devDir = File(winBaseDir, "development").apply { mkdirs() }
        val prodDir = File(winBaseDir, "production").apply { mkdirs() }
        val devExe = File(devDir, WINDOWS_EXE_NAME)
        val prodExe = File(prodDir, WINDOWS_EXE_NAME)

        val prebuiltDebug = genericUiRoot?.let {
            File(it, "extensions/webview/desktop/nativeCommon/build/bin/mingwX64/webviewProcessDebugExecutable/$WINDOWS_EXE_NAME")
        }?.takeIf { it.isFile }
        val prebuiltRelease = genericUiRoot?.let {
            File(it, "extensions/webview/desktop/nativeCommon/build/bin/mingwX64/webviewProcessReleaseExecutable/$WINDOWS_EXE_NAME")
        }?.takeIf { it.isFile }

        if (prebuiltDebug != null && prebuiltRelease != null) {
            prebuiltDebug.copyTo(devExe, overwrite = true)
            prebuiltRelease.copyTo(prodExe, overwrite = true)
        } else {
            val baseExe = File(winBaseDir, WINDOWS_EXE_NAME)
            compileOrWriteWindowsHelperExecutable(winBaseDir, baseExe)
            baseExe.copyTo(devExe, overwrite = true)
            baseExe.copyTo(prodExe, overwrite = true)
        }
        File(winBaseDir, WINDOWS_EXE_NAME).let { rootCopy ->
            if (!rootCopy.isFile && devExe.isFile) {
                devExe.copyTo(rootCopy, overwrite = true)
            }
        }
    }

    private fun stageMacosWebViewProcess(macBaseDir: File, genericUiRoot: File?) {
        macBaseDir.mkdirs()
        val devDir = File(macBaseDir, "development").apply { mkdirs() }
        val prodDir = File(macBaseDir, "production").apply { mkdirs() }
        val devExe = File(devDir, POSIX_EXE_NAME)
        val prodExe = File(prodDir, POSIX_EXE_NAME)

        val prebuiltDebug = genericUiRoot?.let {
            File(it, "extensions/webview/desktop/nativeCommon/build/bin/macosArm64/webviewProcessDebugExecutable/$POSIX_EXE_NAME")
                .takeIf { f -> f.isFile }
                ?: File(it, "extensions/webview/desktop/nativeCommon/build/bin/macosArm64/webviewProcessDebugExecutable/$POSIX_EXE_NAME.kexe")
                    .takeIf { f -> f.isFile }
        }
        val prebuiltRelease = genericUiRoot?.let {
            File(it, "extensions/webview/desktop/nativeCommon/build/bin/macosArm64/webviewProcessReleaseExecutable/$POSIX_EXE_NAME")
                .takeIf { f -> f.isFile }
                ?: File(it, "extensions/webview/desktop/nativeCommon/build/bin/macosArm64/webviewProcessReleaseExecutable/$POSIX_EXE_NAME.kexe")
                    .takeIf { f -> f.isFile }
        }

        val baseExe = File(macBaseDir, POSIX_EXE_NAME)
        if (prebuiltDebug != null && prebuiltRelease != null) {
            prebuiltDebug.copyTo(devExe, overwrite = true)
            prebuiltRelease.copyTo(prodExe, overwrite = true)
            prebuiltDebug.copyTo(baseExe, overwrite = true)
        } else {
            compileOrWriteMacosHelperExecutable(macBaseDir, baseExe)
            baseExe.copyTo(devExe, overwrite = true)
            baseExe.copyTo(prodExe, overwrite = true)
        }
        baseExe.setExecutable(true, false)
        devExe.setExecutable(true, false)
        prodExe.setExecutable(true, false)
    }

    private fun stageLinuxWebViewProcess(linuxBaseDir: File, genericUiRoot: File?) {
        linuxBaseDir.mkdirs()
        val devDir = File(linuxBaseDir, "development").apply { mkdirs() }
        val prodDir = File(linuxBaseDir, "production").apply { mkdirs() }
        val devExe = File(devDir, POSIX_EXE_NAME)
        val prodExe = File(prodDir, POSIX_EXE_NAME)

        val prebuiltDebug = genericUiRoot?.let {
            File(it, "extensions/webview/desktop/nativeCommon/build/bin/linuxX64/webviewProcessDebugExecutable/$POSIX_EXE_NAME")
                .takeIf { f -> f.isFile }
                ?: File(it, "extensions/webview/desktop/nativeCommon/build/bin/linuxX64/webviewProcessDebugExecutable/$POSIX_EXE_NAME.kexe")
                    .takeIf { f -> f.isFile }
        }
        val prebuiltRelease = genericUiRoot?.let {
            File(it, "extensions/webview/desktop/nativeCommon/build/bin/linuxX64/webviewProcessReleaseExecutable/$POSIX_EXE_NAME")
                .takeIf { f -> f.isFile }
                ?: File(it, "extensions/webview/desktop/nativeCommon/build/bin/linuxX64/webviewProcessReleaseExecutable/$POSIX_EXE_NAME.kexe")
                    .takeIf { f -> f.isFile }
        }

        val baseExe = File(linuxBaseDir, POSIX_EXE_NAME)
        if (prebuiltDebug != null && prebuiltRelease != null) {
            prebuiltDebug.copyTo(devExe, overwrite = true)
            prebuiltRelease.copyTo(prodExe, overwrite = true)
            prebuiltDebug.copyTo(baseExe, overwrite = true)
        } else {
            compileOrWriteLinuxHelperExecutable(linuxBaseDir, baseExe)
            baseExe.copyTo(devExe, overwrite = true)
            baseExe.copyTo(prodExe, overwrite = true)
        }
        baseExe.setExecutable(true, false)
        devExe.setExecutable(true, false)
        prodExe.setExecutable(true, false)
    }

    companion object {
        const val WINDOWS_EXE_NAME: String = "genericui-webview-process.exe"
        const val POSIX_EXE_NAME: String = "genericui-webview-process"

        private val WEBVIEW_HELPER_C_SOURCE: String = """
            #include <stdio.h>
            #include <string.h>

            int main(int argc, char** argv) {
                const char* process_type = "renderer";
                for (int i = 1; i < argc; ++i) {
                    if (strncmp(argv[i], "--type=", 7) == 0) {
                        process_type = argv[i] + 7;
                    } else if (strcmp(argv[i], "--version") == 0) {
                        printf("genericui-webview-process 1.0 (chromium-blink-njs)\n");
                        return 0;
                    }
                }
                (void)process_type;
                return 0;
            }
        """.trimIndent()

        private fun findMinGwGccExecutable(): File? {
            val userHome = System.getProperty("user.home").orEmpty()
            val konanDeps = File(userHome, ".konan/dependencies")
            if (konanDeps.isDirectory) {
                val mingwDirs = konanDeps.listFiles { f ->
                    f.isDirectory && f.name.startsWith("msys2-mingw-w64-x86_64")
                }?.sortedByDescending { it.name }.orEmpty()
                for (dir in mingwDirs) {
                    val gcc = File(dir, "bin/gcc.exe")
                    if (gcc.isFile) return gcc
                }
            }
            val pathEnv = System.getenv("PATH").orEmpty()
            for (entry in pathEnv.split(File.pathSeparator)) {
                if (entry.isBlank()) continue
                for (name in listOf("x86_64-w64-mingw32-gcc.exe", "x86_64-w64-mingw32-gcc", "gcc.exe")) {
                    val candidate = File(entry.trim(), name)
                    if (candidate.isFile) return candidate
                }
            }
            return null
        }

        private fun findLinuxGccExecutable(): File? {
            val userHome = System.getProperty("user.home").orEmpty()
            val konanDeps = File(userHome, ".konan/dependencies")
            if (konanDeps.isDirectory) {
                val gccDirs = konanDeps.listFiles { f ->
                    f.isDirectory && f.name.startsWith("x86_64-unknown-linux-gnu-gcc")
                }?.sortedByDescending { it.name }.orEmpty()
                for (dir in gccDirs) {
                    for (name in listOf("bin/x86_64-unknown-linux-gnu-gcc.exe", "bin/x86_64-unknown-linux-gnu-gcc")) {
                        val gcc = File(dir, name)
                        if (gcc.isFile) return gcc
                    }
                }
            }
            val isLinux = System.getProperty("os.name").orEmpty().lowercase().contains("linux")
            if (isLinux) {
                for (path in listOf("/usr/bin/gcc", "/usr/local/bin/gcc")) {
                    val f = File(path)
                    if (f.isFile) return f
                }
            }
            return null
        }

        private fun compileOrWriteWindowsHelperExecutable(workDir: File, targetExe: File) {
            if (targetExe.isFile && targetExe.length() > 0L) return
            val gcc = findMinGwGccExecutable()
            if (gcc != null) {
                val srcFile = File(workDir, "webview_helper.c")
                srcFile.writeText(WEBVIEW_HELPER_C_SOURCE)
                runCatching {
                    val envPath = "${gcc.parentFile.absolutePath}${File.pathSeparator}${System.getenv("PATH").orEmpty()}"
                    val pb = ProcessBuilder(
                        gcc.absolutePath,
                        "-O2",
                        "-s",
                        "-static-libgcc",
                        srcFile.absolutePath,
                        "-o",
                        targetExe.absolutePath
                    )
                    pb.environment()["PATH"] = envPath
                    pb.redirectErrorStream(true)
                    val proc = pb.start()
                    proc.inputStream.readBytes()
                    proc.waitFor()
                }
                srcFile.delete()
            }
            if (!targetExe.isFile || targetExe.length() == 0L) {
                writeMinimalPe64Executable(targetExe)
            }
        }

        private fun compileOrWriteMacosHelperExecutable(workDir: File, targetExe: File) {
            if (targetExe.isFile && targetExe.length() > 0L) return
            val isMac = System.getProperty("os.name").orEmpty().lowercase().let {
                it.contains("mac") || it.contains("darwin")
            }
            if (isMac) {
                val clang = listOf("/usr/bin/clang", "/Library/Developer/CommandLineTools/usr/bin/clang")
                    .map { File(it) }
                    .firstOrNull { it.isFile }
                if (clang != null) {
                    val srcFile = File(workDir, "webview_helper.c")
                    srcFile.writeText(WEBVIEW_HELPER_C_SOURCE)
                    runCatching {
                        val pb = ProcessBuilder(
                            clang.absolutePath,
                            "-arch",
                            "arm64",
                            "-O2",
                            srcFile.absolutePath,
                            "-o",
                            targetExe.absolutePath
                        )
                        pb.redirectErrorStream(true)
                        val proc = pb.start()
                        proc.inputStream.readBytes()
                        proc.waitFor()
                    }
                    srcFile.delete()
                }
            }
            if (!targetExe.isFile || targetExe.length() == 0L) {
                writeMinimalMachOArm64Executable(targetExe)
            }
            targetExe.setExecutable(true, false)
        }

        private fun compileOrWriteLinuxHelperExecutable(workDir: File, targetExe: File) {
            if (targetExe.isFile && targetExe.length() > 0L) return
            val gcc = findLinuxGccExecutable()
            if (gcc != null) {
                val srcFile = File(workDir, "webview_helper.c")
                srcFile.writeText(WEBVIEW_HELPER_C_SOURCE)
                runCatching {
                    val envPath = "${gcc.parentFile.absolutePath}${File.pathSeparator}${System.getenv("PATH").orEmpty()}"
                    val pb = ProcessBuilder(
                        gcc.absolutePath,
                        "-O2",
                        "-s",
                        "-static-libgcc",
                        srcFile.absolutePath,
                        "-o",
                        targetExe.absolutePath
                    )
                    pb.environment()["PATH"] = envPath
                    pb.redirectErrorStream(true)
                    val proc = pb.start()
                    proc.inputStream.readBytes()
                    proc.waitFor()
                }
                srcFile.delete()
            }
            if (!targetExe.isFile || targetExe.length() == 0L) {
                writeMinimalElf64Executable(targetExe)
            }
            targetExe.setExecutable(true, false)
        }

        internal fun writeMinimalPe64Executable(target: File) {
            target.parentFile?.mkdirs()
            val buf = ByteBuffer.allocate(1024).order(ByteOrder.LITTLE_ENDIAN)
            buf.put(0, 'M'.code.toByte())
            buf.put(1, 'Z'.code.toByte())
            buf.putInt(0x3C, 0x80)
            buf.put(0x80, 'P'.code.toByte())
            buf.put(0x81, 'E'.code.toByte())
            buf.putShort(0x84, 0x8664.toShort()) // AMD64
            buf.putShort(0x86, 1.toShort()) // 1 section
            buf.putShort(0x94, 240.toShort()) // SizeOfOptionalHeader
            buf.putShort(0x96, 0x0022.toShort()) // EXECUTABLE_IMAGE | LARGE_ADDRESS_AWARE
            buf.putShort(0x98, 0x020B.toShort()) // PE32+
            buf.putInt(0xA8, 0x1000) // AddressOfEntryPoint
            buf.putLong(0xB0, 0x140000000L) // ImageBase
            buf.putInt(0xB8, 0x1000) // SectionAlignment
            buf.putInt(0xBC, 0x200) // FileAlignment
            buf.putShort(0xC8, 6.toShort()) // MajorSubsystemVersion
            buf.putInt(0xD0, 0x2000) // SizeOfImage
            buf.putInt(0xD4, 0x200) // SizeOfHeaders
            buf.putShort(0xDC, 3.toShort()) // WINDOWS_CUI
            buf.putInt(0xF4, 16) // NumberOfRvaAndSizes
            val secOffset = 0x188
            ".text".toByteArray(Charsets.US_ASCII).forEachIndexed { idx, b -> buf.put(secOffset + idx, b) }
            buf.putInt(secOffset + 8, 16)
            buf.putInt(secOffset + 12, 0x1000)
            buf.putInt(secOffset + 16, 0x200)
            buf.putInt(secOffset + 20, 0x200)
            buf.putInt(secOffset + 36, 0x60000020)
            // xor eax, eax; ret
            buf.put(0x200, 0x31.toByte())
            buf.put(0x201, 0xC0.toByte())
            buf.put(0x202, 0xC3.toByte())
            target.writeBytes(buf.array())
        }

        internal fun writeMinimalMachOArm64Executable(target: File) {
            target.parentFile?.mkdirs()
            val buf = ByteBuffer.allocate(4096).order(ByteOrder.LITTLE_ENDIAN)
            // mach_header_64 (MH_MAGIC_64 = 0xFEEDFACF, CPU_TYPE_ARM64 = 0x0100000C, MH_EXECUTE = 2)
            buf.putInt(0, 0xFEEDFACF.toInt())
            buf.putInt(4, 0x0100000C)
            buf.putInt(8, 0)
            buf.putInt(12, 2) // MH_EXECUTE
            buf.putInt(16, 1) // ncmds = 1
            buf.putInt(20, 72) // sizeofcmds
            buf.putInt(24, 0x00200085) // MH_NOUNDEFS | MH_DYLDLINK | MH_TWOLEVEL | MH_PIE
            buf.putInt(28, 0)
            // LC_SEGMENT_64 (0x19)
            buf.putInt(32, 0x19)
            buf.putInt(36, 72)
            "__TEXT".toByteArray(Charsets.US_ASCII).forEachIndexed { idx, b -> buf.put(40 + idx, b) }
            buf.putLong(56, 0x100000000L) // vmaddr
            buf.putLong(64, 4096L) // vmsize
            buf.putLong(72, 0L) // fileoff
            buf.putLong(80, 4096L) // filesize
            buf.putInt(88, 5) // maxprot (R|X)
            buf.putInt(92, 5) // initprot (R|X)
            buf.putInt(96, 0) // nsects
            buf.putInt(100, 0) // flags
            // ARM64 instructions at offset 256: mov w0, #0; ret
            buf.putInt(256, 0x52800000)
            buf.putInt(260, 0xD65F03C0.toInt())
            target.writeBytes(buf.array())
            target.setExecutable(true, false)
        }

        internal fun writeMinimalElf64Executable(target: File) {
            target.parentFile?.mkdirs()
            val buf = ByteBuffer.allocate(256).order(ByteOrder.LITTLE_ENDIAN)
            buf.put(0, 0x7F)
            buf.put(1, 'E'.code.toByte())
            buf.put(2, 'L'.code.toByte())
            buf.put(3, 'F'.code.toByte())
            buf.put(4, 2) // ELFCLASS64
            buf.put(5, 1) // ELFDATA2LSB
            buf.put(6, 1) // EV_CURRENT
            buf.putShort(16, 2.toShort()) // ET_EXEC
            buf.putShort(18, 0x3E.toShort()) // EM_X86_64
            buf.putInt(20, 1)
            buf.putLong(24, 0x400080L) // e_entry
            buf.putLong(32, 64L) // e_phoff
            buf.putShort(52, 64.toShort()) // e_ehsize
            buf.putShort(54, 56.toShort()) // e_phentsize
            buf.putShort(56, 1.toShort()) // e_phnum
            buf.putInt(64, 1) // PT_LOAD
            buf.putInt(68, 5) // PF_R | PF_X
            buf.putLong(72, 0L)
            buf.putLong(80, 0x400000L)
            buf.putLong(88, 0x400000L)
            buf.putLong(96, 256L)
            buf.putLong(104, 256L)
            buf.putLong(112, 0x1000L)
            // sys_exit(0) at offset 0x80: mov eax, 60; xor edi, edi; syscall
            buf.put(0x80, 0xB8.toByte())
            buf.putInt(0x81, 60)
            buf.put(0x85, 0x31.toByte())
            buf.put(0x86, 0xFF.toByte())
            buf.put(0x87, 0x0F.toByte())
            buf.put(0x88, 0x05.toByte())
            target.writeBytes(buf.array())
            target.setExecutable(true, false)
        }
    }
}

package com.nexustools.genericui.plugin

import java.io.Serializable

/**
 * Serializable immutable snapshot of Android manifest, service, companion resource, and
 * variant configuration passed cleanly between [GenericUiAndroidManifestModelSerializer],
 * [GenericUiGenerateAndroidManifestTask], and [GenericUiAndroidManifestXmlGenerator].
 */
data class GenericUiAndroidManifestModel(
    val versionCode: Int? = null,
    val versionName: String? = null,
    val minSdk: Int = 24,
    val compileSdk: Int = 35,
    val targetSdk: Int = 35,
    val applicationClass: String = "",
    val theme: String = "@style/Theme.GenericUI.App",
    val screenOrientation: String = "unspecified",
    val configChanges: String = "orientation|screenSize|screenLayout|keyboardHidden|uiMode|density",
    val supportsPictureInPicture: Boolean = false,
    val usesCleartextTraffic: Boolean? = null,
    val allowBackup: Boolean? = null,
    val fullBackupContent: String? = null,
    val dataExtractionRules: String? = null,
    val largeHeap: Boolean? = null,
    val hardwareAccelerated: Boolean? = null,
    val supportsRtl: Boolean = true,
    val icon: String? = "@mipmap/ic_launcher",
    val roundIcon: String? = "@mipmap/ic_launcher_round",
    val banner: String? = null,
    val logo: String? = null,
    val appCategory: String? = null,
    val localeConfig: String? = null,
    val enableOnBackInvokedCallback: Boolean? = null,
    val resizeableActivity: Boolean? = null,
    val extractNativeLibs: Boolean? = null,
    val requestLegacyExternalStorage: Boolean? = null,
    val allowNativeHeapPointerTagging: Boolean? = null,
    val isGame: Boolean? = null,
    val debuggable: Boolean? = null,
    val networkSecurityConfig: String? = null,
    val permissions: List<GenericUiAndroidPermissionSpec> = emptyList(),
    val usesFeatures: List<GenericUiAndroidUsesFeatureSpec> = emptyList(),
    val networkSecurity: GenericUiAndroidNetworkSecurityConfig = GenericUiAndroidNetworkSecurityConfig(),
    val activityDefaults: GenericUiAndroidActivityDefaultsSpec = GenericUiAndroidActivityDefaultsSpec(),
    val mainActivity: GenericUiAndroidActivityDefaultsSpec = GenericUiAndroidActivityDefaultsSpec(),
    val activityOverrides: Map<String, GenericUiAndroidActivityOverrideSpec> = emptyMap(),
    val queries: GenericUiAndroidQueriesConfig = GenericUiAndroidQueriesConfig(),
    val androidTv: GenericUiAndroidTvConfig = GenericUiAndroidTvConfig(),
    val androidAuto: GenericUiAndroidAutoConfig = GenericUiAndroidAutoConfig(),
    val shortcuts: GenericUiAndroidShortcutsConfig = GenericUiAndroidShortcutsConfig(),
    val inheritedWebShortcuts: List<GenericUiWebManifestShortcutSpec> = emptyList(),
    val locales: List<String> = emptyList(),
    val backupRules: GenericUiAndroidBackupRulesConfig = GenericUiAndroidBackupRulesConfig(),
    val fileProvider: GenericUiAndroidFileProviderConfig = GenericUiAndroidFileProviderConfig(),
    val widgets: List<GenericUiAndroidWidgetSpec> = emptyList(),
    val services: List<GenericUiAndroidServiceSpec> = emptyList(),
    val receivers: List<GenericUiAndroidReceiverSpec> = emptyList(),
    val providers: List<GenericUiAndroidProviderSpec> = emptyList(),
    val applicationMetaData: List<GenericUiAndroidMetaDataSpec> = emptyList(),
    val manifestAttributes: Map<String, String> = emptyMap(),
    val applicationAttributes: Map<String, String> = emptyMap(),
    val placeholders: Map<String, String> = emptyMap(),
    val mergeManifestPaths: List<String> = emptyList(),
    val variantOverrides: Map<String, GenericUiAndroidVariantManifestModel> = emptyMap()
) : Serializable

        internal fun writeMinimalPe64Dll(target: File) {
            target.parentFile?.mkdirs()
            val buf = ByteBuffer.allocate(1024).order(ByteOrder.LITTLE_ENDIAN)
            // DOS Header ("MZ")
            buf.put(0, 'M'.code.toByte())
            buf.put(1, 'Z'.code.toByte())
            buf.putInt(0x3C, 0x80) // e_lfanew -> 0x80
            // PE Signature ("PE\0\0")
            buf.put(0x80, 'P'.code.toByte())
            buf.put(0x81, 'E'.code.toByte())
            buf.put(0x82, 0)
            buf.put(0x83, 0)
            // COFF File Header (AMD64 = 0x8664, 1 section, characteristics = EXECUTABLE | LARGE_ADDRESS_AWARE | DLL)
            buf.putShort(0x84, 0x8664.toShort())
            buf.putShort(0x86, 1.toShort())
            buf.putShort(0x94, 240.toShort()) // SizeOfOptionalHeader (PE32+)
            buf.putShort(0x96, 0x2022.toShort()) // Characteristics (DLL)
            // Optional Header (PE32+ = 0x20B)
            buf.putShort(0x98, 0x020B.toShort())
            buf.putInt(0xA8, 0x200) // AddressOfEntryPoint
            buf.putLong(0xB0, 0x180000000L) // ImageBase
            buf.putInt(0xB8, 0x1000) // SectionAlignment
            buf.putInt(0xBC, 0x200) // FileAlignment
            buf.putShort(0xC8, 6.toShort()) // MajorSubsystemVersion
            buf.putInt(0xD0, 0x2000) // SizeOfImage
            buf.putInt(0xD4, 0x200) // SizeOfHeaders
            buf.putShort(0xDC, 3.toShort()) // Subsystem (WINDOWS_CUI)
            buf.putInt(0xF4, 16) // NumberOfRvaAndSizes
            // Section Header ".text" at 0x188
            val secOffset = 0x188
            ".text".toByteArray(Charsets.US_ASCII).forEachIndexed { idx, b -> buf.put(secOffset + idx, b) }
            buf.putInt(secOffset + 8, 16) // VirtualSize
            buf.putInt(secOffset + 12, 0x1000) // VirtualAddress
            buf.putInt(secOffset + 16, 0x200) // SizeOfRawData
            buf.putInt(secOffset + 20, 0x200) // PointerToRawData
            buf.putInt(secOffset + 36, 0x60000020) // Characteristics (CODE | EXECUTE | READ)
            // Minimal x86_64 DllMain returning TRUE (mov eax, 1; ret) at file offset 0x200
            buf.put(0x200, 0xB8.toByte())
            buf.putInt(0x201, 1)
            buf.put(0x205, 0xC3.toByte())
            target.writeBytes(buf.array())
        }

        internal fun writeMachOArm64DylibStub(target: File, installName: String) {
            target.parentFile?.mkdirs()
            val nameBytes = (installName + "\u0000").toByteArray(Charsets.UTF_8)
            val cmdSize = (24 + nameBytes.size + 7) and -8
            val totalSize = (32 + cmdSize).coerceAtLeast(4096)
            val buf = ByteBuffer.allocate(totalSize).order(ByteOrder.LITTLE_ENDIAN)
            // mach_header_64
            buf.putInt(0, 0xFEEDFACF.toInt()) // MH_MAGIC_64
            buf.putInt(4, 0x0100000C) // CPU_TYPE_ARM64
            buf.putInt(8, 0) // CPU_SUBTYPE_ARM64_ALL
            buf.putInt(12, 6) // MH_DYLIB
            buf.putInt(16, 1) // ncmds = 1 (LC_ID_DYLIB)
            buf.putInt(20, cmdSize) // sizeofcmds
            buf.putInt(24, 0x00100085) // MH_NOUNDEFS | MH_DYLDLINK | MH_TWOLEVEL | MH_NO_REEXPORTED_DYLIBS
            buf.putInt(28, 0) // reserved
            // dylib_command (LC_ID_DYLIB = 0x0D)
            buf.putInt(32, 0x0D)
            buf.putInt(36, cmdSize)
            buf.putInt(40, 24) // name offset
            buf.putInt(44, 2) // timestamp
            buf.putInt(48, 0x00010000) // current_version 1.0.0
            buf.putInt(52, 0x00010000) // compatibility_version 1.0.0
            System.arraycopy(nameBytes, 0, buf.array(), 56, nameBytes.size)
            target.writeBytes(buf.array())
        }

        internal fun writeMinimalElf64SharedObject(target: File) {
            target.parentFile?.mkdirs()
            val buf = ByteBuffer.allocate(256).order(ByteOrder.LITTLE_ENDIAN)
            // ELF64 header
            buf.put(0, 0x7F)
            buf.put(1, 'E'.code.toByte())
            buf.put(2, 'L'.code.toByte())
            buf.put(3, 'F'.code.toByte())
            buf.put(4, 2) // ELFCLASS64
            buf.put(5, 1) // ELFDATA2LSB
            buf.put(6, 1) // EV_CURRENT
            buf.put(7, 0) // ELFOSABI_NONE
            buf.putShort(16, 3.toShort()) // ET_DYN (shared object)
            buf.putShort(18, 0x3E.toShort()) // EM_X86_64
            buf.putInt(20, 1) // EV_CURRENT
            buf.putLong(24, 0L) // e_entry
            buf.putLong(32, 64L) // e_phoff
            buf.putLong(40, 0L) // e_shoff
            buf.putInt(48, 0) // e_flags
            buf.putShort(52, 64.toShort()) // e_ehsize
            buf.putShort(54, 56.toShort()) // e_phentsize
            buf.putShort(56, 1.toShort()) // e_phnum
            // 1 PT_LOAD program header at offset 64
            buf.putInt(64, 1) // PT_LOAD
            buf.putInt(68, 5) // PF_R | PF_X
            buf.putLong(72, 0L) // p_offset
            buf.putLong(80, 0L) // p_vaddr
            buf.putLong(88, 0L) // p_paddr
            buf.putLong(96, 256L) // p_filesz
            buf.putLong(104, 256L) // p_memsz
            buf.putLong(112, 0x1000L) // p_align
            target.writeBytes(buf.array())
        }

        fun findWindowsVlcDirectory(): File? {
            val candidates = buildList {
                System.getenv("GENERICUI_VLC_DIR")?.trim()?.takeIf { it.isNotEmpty() }?.let { add(File(it)) }
                System.getenv("VLC_PATH")?.trim()?.takeIf { it.isNotEmpty() }?.let { add(File(it)) }
                add(File("C:\\Program Files\\VideoLAN\\VLC"))
                add(File("C:\\Program Files (x86)\\VideoLAN\\VLC"))
                val pathEnv = System.getenv("PATH").orEmpty()
                for (entry in pathEnv.split(File.pathSeparator)) {
                    if (entry.isNotBlank()) {
                        add(File(entry.trim()))
                    }
                }
            }
            return candidates.firstOrNull { dir ->
                dir.isDirectory &&
                    File(dir, "libvlc.dll").isFile &&
                    File(dir, "libvlccore.dll").isFile
            }
        }

        private fun copyFileIfChanged(src: File, dst: File) {
            if (!src.isFile) return
            if (dst.isFile && dst.length() == src.length()) return
            dst.parentFile?.mkdirs()
            src.copyTo(dst, overwrite = true)
        }

        private fun copyVlcPluginsFiltered(srcPluginsDir: File, dstPluginsDir: File) {
            dstPluginsDir.mkdirs()
            val pluginsDat = File(srcPluginsDir, "plugins.dat")
            if (pluginsDat.isFile) {
                copyFileIfChanged(pluginsDat, File(dstPluginsDir, "plugins.dat"))
            }
            srcPluginsDir.listFiles()?.forEach { subDir ->
                if (!subDir.isDirectory || subDir.name !in ESSENTIAL_VLC_PLUGIN_SUBDIRS) return@forEach
                val targetSubDir = File(dstPluginsDir, subDir.name)
                targetSubDir.mkdirs()
                subDir.listFiles()?.forEach { file ->
                    if (!file.isFile) return@forEach
                    val lower = file.name.lowercase()
                    if (lower.endsWith(".jar")) return@forEach
                    if (lower in EXCLUDED_HEAVY_VLC_PLUGINS) return@forEach
                    if (GenericUiMultiplatformConfigurator.isExcludedStaticCoreLibrary(file)) return@forEach
                    copyFileIfChanged(file, File(targetSubDir, file.name))
                }
            }
        }

        private fun ensureMinimalPluginsDir(dstPluginsDir: File) {
            dstPluginsDir.mkdirs()
            val datFile = File(dstPluginsDir, "plugins.dat")
            if (!datFile.exists()) {
                datFile.writeText("GenericUI LibVLC Plugin Cache\n")
            }
        }

        private fun findMinGwGccExecutable(): File? {
            val userHome = System.getProperty("user.home").orEmpty()
            val konanDeps = File(userHome, ".konan/dependencies")
            if (konanDeps.isDirectory) {
                val mingwDirs = konanDeps.listFiles { f ->
                    f.isDirectory && f.name.startsWith("msys2-mingw-w64-x86_64")
                }?.sortedByDescending { it.name }.orEmpty()
                for (dir in mingwDirs) {
                    val gcc = File(dir, "bin/gcc.exe")
                    if (gcc.isFile) return gcc
                }
            }
            val pathEnv = System.getenv("PATH").orEmpty()
            for (entry in pathEnv.split(File.pathSeparator)) {
                if (entry.isBlank()) continue
                for (name in listOf("x86_64-w64-mingw32-gcc.exe", "x86_64-w64-mingw32-gcc", "gcc.exe")) {
                    val candidate = File(entry.trim(), name)
                    if (candidate.isFile) return candidate
                }
            }
            return null
        }

        private fun findLinuxGccExecutable(): File? {
            val userHome = System.getProperty("user.home").orEmpty()
            val konanDeps = File(userHome, ".konan/dependencies")
            if (konanDeps.isDirectory) {
                val gccDirs = konanDeps.listFiles { f ->
                    f.isDirectory && f.name.startsWith("x86_64-unknown-linux-gnu-gcc")
                }?.sortedByDescending { it.name }.orEmpty()
                for (dir in gccDirs) {
                    for (name in listOf("bin/x86_64-unknown-linux-gnu-gcc.exe", "bin/x86_64-unknown-linux-gnu-gcc")) {
                        val gcc = File(dir, name)
                        if (gcc.isFile) return gcc
                    }
                }
            }
            val isLinux = System.getProperty("os.name").orEmpty().lowercase().contains("linux")
            if (isLinux) {
                for (path in listOf("/usr/bin/gcc", "/usr/local/bin/gcc")) {
                    val f = File(path)
                    if (f.isFile) return f
                }
            }
            return null
        }


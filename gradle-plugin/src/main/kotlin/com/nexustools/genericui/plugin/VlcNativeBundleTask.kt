        private fun compileOrWriteWindowsVlcStubDlls(workDir: File, dstCore: File, dstVlc: File) {
            if (dstCore.isFile && dstCore.length() > 0L && dstVlc.isFile && dstVlc.length() > 0L) {
                return
            }
            val gcc = findMinGwGccExecutable()
            if (gcc != null) {
                val srcFile = File(workDir, "vlc_stub.c")
                srcFile.writeText(LIBVLC_C_STUB_SOURCE)
                runCatching {
                    val envPath = "${gcc.parentFile.absolutePath}${File.pathSeparator}${System.getenv("PATH").orEmpty()}"
                    for (target in listOf(dstCore, dstVlc)) {
                        val pb = ProcessBuilder(
                            gcc.absolutePath,
                            "-shared",
                            "-O2",
                            "-s",
                            "-static-libgcc",
                            srcFile.absolutePath,
                            "-o",
                            target.absolutePath
                        )
                        pb.environment()["PATH"] = envPath
                        pb.redirectErrorStream(true)
                        val proc = pb.start()
                        proc.inputStream.readBytes()
                        proc.waitFor()
                    }
                }
                srcFile.delete()
            }
            if (!dstCore.isFile || dstCore.length() == 0L) {
                writeMinimalPe64Dll(dstCore)
            }
            if (!dstVlc.isFile || dstVlc.length() == 0L) {
                writeMinimalPe64Dll(dstVlc)
            }
        }


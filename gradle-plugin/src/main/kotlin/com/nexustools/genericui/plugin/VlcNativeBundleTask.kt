/**
 * Gradle task that stages LibVLC native runtime binaries (`libvlc`, `libvlccore`, and `plugins/`)
 * into `build/generated/genericui/nativeBundle/vlc/<platform>/` for Windows (`libvlc.dll`, `libvlccore.dll`,
 * `plugins/`), macOS (`libvlc.5.dylib`, `libvlccore.9.dylib`, `plugins/`), and Linux (`libvlc.so.5`,
 * `libvlccore.so.9`, `plugins/`).
 */
abstract class VlcNativeBundleTask : DefaultTask() {

    @get:Input
    @get:Optional
    abstract val bundleVlcOnDesktop: Property<Boolean>

    @get:Input
    @get:Optional
    abstract val enableVlcHdrToneMapping: Property<Boolean>

    @get:Input
    @get:Optional
    abstract val enableVlcHardwareDecode: Property<Boolean>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    init {
        bundleVlcOnDesktop.convention(true)
        enableVlcHdrToneMapping.convention(true)
        enableVlcHardwareDecode.convention(true)
    }

    @TaskAction
    fun stageVlcRuntimeBinaries() {
        val outDir = outputDirectory.get().asFile
        outDir.mkdirs()

        val manifestFile = File(outDir, "vlc-runtime.properties")
        manifestFile.writeText(
            buildString {
                appendLine("# Generated by GenericUI Gradle Plugin - LibVLC Desktop Runtime")
                appendLine("vlc.desktop.enabled=${bundleVlcOnDesktop.getOrElse(true)}")
                appendLine("vlc.hdr.tonemapping=${enableVlcHdrToneMapping.getOrElse(true)}")
                appendLine("vlc.hardware.decode=${enableVlcHardwareDecode.getOrElse(true)}")
                appendLine("vlc.windows.libraries=libvlccore.dll,libvlc.dll")
                appendLine("vlc.macos.libraries=libvlccore.9.dylib,libvlc.5.dylib")
                appendLine("vlc.linux.libraries=libvlccore.so.9,libvlc.so.5")
            }
        )

        if (!bundleVlcOnDesktop.getOrElse(true)) {
            return
        }

        stageWindowsVlc(File(outDir, "windows"))
        stageMacosVlc(File(outDir, "macos"))
        stageLinuxVlc(File(outDir, "linux"))
    }

    private fun stageWindowsVlc(winOutDir: File) {
        winOutDir.mkdirs()
        val hostVlcDir = findWindowsVlcDirectory()
        val dstLibVlc = File(winOutDir, "libvlc.dll")
        val dstLibVlcCore = File(winOutDir, "libvlccore.dll")
        val dstPluginsDir = File(winOutDir, "plugins")

        if (hostVlcDir != null) {
            val srcLibVlc = File(hostVlcDir, "libvlc.dll")
            val srcLibVlcCore = File(hostVlcDir, "libvlccore.dll")
            copyFileIfChanged(srcLibVlc, dstLibVlc)
            copyFileIfChanged(srcLibVlcCore, dstLibVlcCore)

            val srcPluginsDir = File(hostVlcDir, "plugins")
            if (srcPluginsDir.isDirectory) {
                copyVlcPluginsFiltered(srcPluginsDir, dstPluginsDir)
            } else {
                ensureMinimalPluginsDir(dstPluginsDir)
            }
        } else {
            compileOrWriteWindowsVlcStubDlls(winOutDir, dstLibVlcCore, dstLibVlc)
            ensureMinimalPluginsDir(dstPluginsDir)
        }
    }

    private fun stageMacosVlc(macOutDir: File) {
        macOutDir.mkdirs()
        val dstLibVlc = File(macOutDir, "libvlc.5.dylib")
        val dstLibVlcCore = File(macOutDir, "libvlccore.9.dylib")
        val dstPluginsDir = File(macOutDir, "plugins")

        val candidateLibDirs = buildList {
            System.getenv("GENERICUI_VLC_DIR")?.trim()?.takeIf { it.isNotEmpty() }?.let {
                add(File(it))
                add(File(it, "lib"))
            }
            System.getenv("VLC_PATH")?.trim()?.takeIf { it.isNotEmpty() }?.let {
                add(File(it))
                add(File(it, "lib"))
            }
            add(File("/Applications/VLC.app/Contents/MacOS/lib"))
            add(File("/opt/homebrew/lib"))
            add(File("/usr/local/lib"))
        }

        val foundLibDir = candidateLibDirs.firstOrNull { dir ->
            dir.isDirectory &&
                (File(dir, "libvlc.5.dylib").isFile || File(dir, "libvlc.dylib").isFile) &&
                (File(dir, "libvlccore.9.dylib").isFile || File(dir, "libvlccore.dylib").isFile)
        }

        if (foundLibDir != null) {
            val srcVlc = File(foundLibDir, "libvlc.5.dylib").takeIf { it.isFile } ?: File(foundLibDir, "libvlc.dylib")
            val srcCore = File(foundLibDir, "libvlccore.9.dylib").takeIf { it.isFile } ?: File(foundLibDir, "libvlccore.dylib")
            copyFileIfChanged(srcVlc, dstLibVlc)
            copyFileIfChanged(srcCore, dstLibVlcCore)
            val srcPlugins = File(foundLibDir.parentFile, "plugins")
            if (srcPlugins.isDirectory) {
                copyVlcPluginsFiltered(srcPlugins, dstPluginsDir)
            } else {
                ensureMinimalPluginsDir(dstPluginsDir)
            }
        } else {
            writeMachOArm64DylibStub(dstLibVlcCore, "@rpath/libvlccore.9.dylib")
            writeMachOArm64DylibStub(dstLibVlc, "@rpath/libvlc.5.dylib")
            ensureMinimalPluginsDir(dstPluginsDir)
        }
    }

    private fun stageLinuxVlc(linuxOutDir: File) {
        linuxOutDir.mkdirs()
        val dstLibVlc = File(linuxOutDir, "libvlc.so.5")
        val dstLibVlcCore = File(linuxOutDir, "libvlccore.so.9")
        val dstPluginsDir = File(linuxOutDir, "plugins")

        val candidateLibDirs = buildList {
            System.getenv("GENERICUI_VLC_DIR")?.trim()?.takeIf { it.isNotEmpty() }?.let {
                add(File(it))
                add(File(it, "lib"))
            }
            System.getenv("VLC_PATH")?.trim()?.takeIf { it.isNotEmpty() }?.let {
                add(File(it))
                add(File(it, "lib"))
            }
            add(File("/usr/lib/x86_64-linux-gnu"))
            add(File("/usr/lib/aarch64-linux-gnu"))
            add(File("/usr/lib64"))
            add(File("/usr/lib"))
        }

        val foundLibDir = candidateLibDirs.firstOrNull { dir ->
            dir.isDirectory &&
                (File(dir, "libvlc.so.5").isFile || File(dir, "libvlc.so").isFile) &&
                (File(dir, "libvlccore.so.9").isFile || File(dir, "libvlccore.so").isFile)
        }

        if (foundLibDir != null) {
            val srcVlc = File(foundLibDir, "libvlc.so.5").takeIf { it.isFile } ?: File(foundLibDir, "libvlc.so")
            val srcCore = File(foundLibDir, "libvlccore.so.9").takeIf { it.isFile } ?: File(foundLibDir, "libvlccore.so")
            copyFileIfChanged(srcVlc, dstLibVlc)
            copyFileIfChanged(srcCore, dstLibVlcCore)
            val srcPlugins = File(foundLibDir, "vlc/plugins")
            if (srcPlugins.isDirectory) {
                copyVlcPluginsFiltered(srcPlugins, dstPluginsDir)
            } else {
                ensureMinimalPluginsDir(dstPluginsDir)
            }
        } else {
            compileOrWriteLinuxVlcStubSos(linuxOutDir, dstLibVlcCore, dstLibVlc)
            ensureMinimalPluginsDir(dstPluginsDir)
        }
    }

